ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS banner_style text NOT NULL DEFAULT 'ink';
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS pronouns varchar(32) NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS public.profile_staff_roles (
 profile_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
 role text NOT NULL CHECK(role IN ('developer','moderator','admin','owner')),
 granted_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
 granted_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.profile_staff_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id uuid NOT NULL REFERENCES public.profiles(id),
 target_id uuid NOT NULL REFERENCES public.profiles(id),
 action text NOT NULL CHECK(action IN ('role','verification')),
 old_value text NOT NULL,
 new_value text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS profile_staff_audit_created_at_idx ON public.profile_staff_audit(created_at DESC);
