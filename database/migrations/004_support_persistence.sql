-- Kova 0.6: additive support ticket upgrades; existing threads retained.
ALTER TABLE public.support_tickets ADD COLUMN IF NOT EXISTS priority text NOT NULL DEFAULT 'normal'
 CHECK (priority IN ('normal','high','urgent'));
ALTER TABLE public.support_tickets ADD COLUMN IF NOT EXISTS last_staff_read_at timestamptz;
ALTER TABLE public.support_tickets ADD COLUMN IF NOT EXISTS last_user_read_at timestamptz;
ALTER TABLE public.support_tickets ADD COLUMN IF NOT EXISTS last_staff_reply_at timestamptz;
ALTER TABLE public.support_tickets ADD COLUMN IF NOT EXISTS last_user_reply_at timestamptz;
CREATE TABLE IF NOT EXISTS public.support_ticket_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id uuid NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
 actor_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 event_type text NOT NULL CHECK (event_type IN ('created','status_changed','priority_changed','assigned','reopened')),
 details jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ticket_events_ticket_time ON public.support_ticket_events(ticket_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_tickets_priority_queue ON public.support_tickets(status,priority,updated_at DESC);
UPDATE public.support_tickets t SET
 last_user_reply_at=(SELECT max(m.created_at) FROM public.support_ticket_messages m WHERE m.ticket_id=t.id AND m.is_staff=false),
 last_staff_reply_at=(SELECT max(m.created_at) FROM public.support_ticket_messages m WHERE m.ticket_id=t.id AND m.is_staff=true)
WHERE t.last_user_reply_at IS NULL AND t.last_staff_reply_at IS NULL;
UPDATE public.support_tickets SET priority='high' WHERE category='safety' AND priority='normal';
