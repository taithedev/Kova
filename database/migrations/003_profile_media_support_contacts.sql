-- Kova v0.5 - additive only; don't reset existing users.
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS avatar_key text;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS banner_key text;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS banner_animated boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.profile_media (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), owner_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 kind text NOT NULL CHECK(kind IN ('avatar','banner')), object_key text NOT NULL UNIQUE,
 mime text NOT NULL, byte_length bigint NOT NULL CHECK(byte_length > 0 AND byte_length <= 15000000),
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 created_at timestamptz NOT NULL DEFAULT now(), reviewed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL, reviewed_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_profile_media_pending ON public.profile_media(status,created_at) WHERE status='pending';
CREATE INDEX IF NOT EXISTS idx_profile_media_owner ON public.profile_media(owner_id,created_at DESC);
CREATE TABLE IF NOT EXISTS public.account_contacts (
 profile_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
 email_encrypted text, phone_encrypted text,
 email_verified boolean NOT NULL DEFAULT false,
 phone_verified boolean NOT NULL DEFAULT false, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.support_tickets (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), author_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 subject varchar(100) NOT NULL, category text NOT NULL CHECK(category IN ('account','technical','safety','other')),
 status text NOT NULL DEFAULT 'open' CHECK(status IN ('open','in_progress','resolved','closed')),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 assigned_to uuid REFERENCES public.profiles(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_support_tickets_author ON public.support_tickets(author_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_tickets_queue ON public.support_tickets(status,created_at DESC);
CREATE TABLE IF NOT EXISTS public.support_ticket_messages (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), ticket_id uuid NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
 author_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 body varchar(2000) NOT NULL CHECK(length(trim(body))>0),is_staff boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_support_ticket_messages_ticket ON public.support_ticket_messages(ticket_id,created_at);
CREATE TABLE IF NOT EXISTS public.staff_action_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 action varchar(60) NOT NULL,subject_type varchar(40) NOT NULL, subject_id uuid,
 detail jsonb NOT NULL DEFAULT '{}'::jsonb, created_at timestamptz NOT NULL DEFAULT now()
);
